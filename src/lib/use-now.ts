"use client";

import { useSyncExternalStore } from "react";

/**
 * เวลาปัจจุบัน ที่อ่านได้เฉพาะบนเบราว์เซอร์หลัง mount แล้วเท่านั้น
 *
 * ทำไมต้องมีฮุกนี้แทนการเรียก `new Date()` ตรง ๆ:
 * Next.js สร้าง HTML ของหน้าไว้ล่วงหน้าตอน build การอ่านนาฬิการะหว่าง render
 * จะทำให้ผลลัพธ์ของหน้าขึ้นกับ "ตอนที่ build" ไม่ใช่ "ตอนที่เด็กเปิด" ซึ่ง
 * ผิดแน่สำหรับคิวทบทวนที่เปลี่ยนทุกวัน — Next จึงทำให้ build พังทันที
 * (ดู blocking-prerender-current-time) และ React Compiler ก็ห้ามด้วยเหตุผลเดียวกัน
 *
 * ฝั่งเซิร์ฟเวอร์จึงคืน null แล้วหน้าค่อยวาดส่วนที่ต้องใช้เวลาหลัง mount
 */

/** เวลาไม่ต้อง subscribe อะไร เราอ่านครั้งเดียวตอนเปิดหน้า */
const noopSubscribe = () => () => {};

/**
 * แคชไว้ในโมดูล เพราะ getSnapshot ต้องคืนค่าเดิมทุกครั้งที่ถูกเรียก
 * ไม่งั้น React จะมองว่าค่าเปลี่ยนตลอดแล้ววาดซ้ำไม่จบ
 *
 * ผลข้างเคียงที่ตั้งใจ: เวลานี้นิ่งตลอดอายุของแท็บ คิวทบทวนจึงไม่ขยับ
 * ใต้มือเด็กระหว่างเล่น ถ้าเปิดแท็บค้างข้ามวันต้องรีโหลดถึงจะได้คิวของวันใหม่
 */
let cached: Date | null = null;

export function useNow(): Date | null {
  return useSyncExternalStore(
    noopSubscribe,
    () => (cached ??= new Date()),
    () => null,
  );
}
