import type { ListenFailure } from "./types";

/**
 * แปลงสาเหตุที่ไมค์ไม่สำเร็จเป็นประโยคไทยที่เด็กอ่านรู้เรื่อง
 *
 * `ListenFailure` เป็นรหัสของเบราว์เซอร์ เช่น "not-allowed" ซึ่งโชว์ให้เด็ก
 * เห็นตรง ๆ ไม่ได้ — เจอจริงตอนต่อไมค์เข้าหน้าแชทครั้งแรก หน้าจอขึ้นคำว่า
 * "not-allowed" ลอยอยู่กลางจอ ซึ่งเด็กไม่รู้ว่าต้องทำอะไรต่อ
 *
 * ตารางนี้เคยถูกคัดลอกไว้ในสองหน้าจอ และต่างกันเล็กน้อยตรงคำกริยา
 * (หน้าเกมพูดใช้ "พูด" หน้าอ่านออกเสียงใช้ "อ่าน") จึงรับคำกริยาเป็น
 * พารามิเตอร์แทนที่จะรวมเป็นข้อความเดียว ไม่งั้นหน้าใดหน้าหนึ่งจะอ่านแปลก
 */
export function micFailureMessage(
  reason: ListenFailure,
  action: "พูด" | "อ่าน" = "พูด",
): string {
  switch (reason) {
    case "no-speech":
      return `ยังไม่ได้ยินเสียงเลย ลอง${action}ดัง ๆ อีกครั้งนะ`;
    case "not-allowed":
      return "เบราว์เซอร์ยังไม่ได้อนุญาตให้ใช้ไมโครโฟน";
    case "audio-capture":
      return "เปิดไมโครโฟนไม่ได้ ลองเช็คว่ามีโปรแกรมอื่นใช้อยู่ไหม";
    case "network":
      return "ต่อเน็ตไม่ได้ การตรวจเสียงต้องใช้อินเทอร์เน็ต";
    case "aborted":
      return `หยุดกลางทาง ลอง${action}อีกครั้งได้เลย`;
    default:
      return "ตรวจเสียงไม่สำเร็จ ลองอีกครั้งนะ";
  }
}
