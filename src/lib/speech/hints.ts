/** จำนวนคำแนะนำสูงสุดที่โชว์พร้อมกัน — มากกว่านี้เด็กไม่อ่าน */
const MAX_HINTS = 2;

/**
 * คำแนะนำสำหรับคำหนึ่ง เรียงจากข้อที่สำคัญที่สุด
 *
 * คำที่ไม่มีเสียงยากเลยจะได้ลิสต์ว่าง ซึ่งถูกต้อง — ดีกว่าแต่งคำแนะนำ
 * ที่ไม่เกี่ยวกับคำนั้นขึ้นมาเติมให้ครบจำนวน
 */
export function hintsForWord(ipa: string): PronunciationHint[] {
  return HINTS.filter((hint) => hint.applies(ipa))
    .slice(0, MAX_HINTS)
    .map(({ id, sound, tip }) => ({ id, sound, tip }));
}
