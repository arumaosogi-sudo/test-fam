/**
 * คำสั้นที่ต้องเทียบตรงตัว เพราะรูปยืดจะไปชนคำปกติ
 *
 * เช่น "ass" ยืดแล้วชน "as" และ "fuk" ยืดแล้วชน "fu" จึงต้องไล่เขียนรูปที่
 * พบจริงเอาเอง แลกกับการพลาดรูปแปลก ๆ บางรูป ซึ่งยอมรับได้
 */
