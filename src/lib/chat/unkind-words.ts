/**
 * คำหยาบไทย — เทียบแบบหาคำย่อยเพราะภาษาไทยไม่เว้นวรรคระหว่างคำ
 *
 * ต้องระวังมากกว่าฝั่งอังกฤษ เพราะการหาคำย่อยชนคำปกติได้ง่าย —
 * "หี" อยู่ใน "หีบ", "กู" อยู่ใน "กูเกิล" (ซึ่งเด็กเพิ่งถามถึงจริง ๆ),
 * "สัส" ใกล้กับ "สัตว์" ที่เป็นคำในบทเรียน คำพวกนี้จึงต้องไม่อยู่ในรายการ
 * หรือต้องเขียนในรูปที่ยาวพอจะไม่ชนอย่างอื่น
 */
const THAI = [
  "เหี้ย",
  "ควย",
  "เย็ด",
  "อีดอก",
  "กระหรี่",
  // "สัส" ปลอดภัยเพราะตัวที่สามต่างจาก "สัตว์" (ส-ั-ส กับ ส-ั-ต-ว-์)
  // แต่ "แม่ง" ใส่ไม่ได้ เพราะไปชน "แม่งาน" ที่เป็นคำปกติ
  "สัส",
  "ชิบหาย",
  "ฉิบหาย",
];

/**
 * มีคำหยาบหรือคำเหยียดในข้อความนี้ไหม
 *
 * ตัดด้วยช่องว่างและเครื่องหมายวรรคตอน แล้วเทียบทีละคำ ไม่ใช่หาคำย่อยทั้งก้อน
 * เพราะการหาคำย่อยในภาษาอังกฤษทำให้ "class" กับ "bass" โดนไปด้วย
 */
export function hasUnkindWord(input: string): boolean {
  if (THAI.some((word) => input.includes(word))) return true;

  /*
   * ตรวจสองรอบ รอบแรกตามคำปกติ รอบสองหลังดึงตัวคั่นกลางคำออก
   *
   * "f*u*c*k" กับ "s.h.i.t" ถ้าตัดด้วยเครื่องหมายวรรคตอนตามปกติจะกลายเป็น
   * ตัวอักษรเดี่ยว ๆ ที่ไม่ตรงกับอะไรเลย ต้องดึงตัวคั่นออกก่อนแล้วตัดใหม่
   *
   * ตั้งใจไม่ดึง "ช่องว่าง" ออกด้วย เพราะจะทำให้ทั้งประโยครวมเป็นคำเดียว
   * แล้วคำปกติที่อยู่ติดกันกลายเป็นคำหยาบได้ เช่น "as s" จะกลายเป็น "ass"
   */
  const SPLIT = /[^A-Za-z0-9!@$]+/;
  const joined = input.replace(/[*._\-+'"/\\|]/g, "");
  const tokens = [...input.split(SPLIT), ...joined.split(SPLIT)].filter(Boolean);

  return tokens.some((token) => {
    const word = normalize(token);
    if (word.length === 0) return false;
    if (EXACT.has(word)) return true;
    return STRETCHABLE.some((pattern) => pattern.test(word));
  });
}

