/**
 * ตัดคำแปลไทยในวงเล็บออกก่อนส่งให้ตัวอ่านออกเสียง
 *
 * ระดับ Pre-A1 กับ A1 อนุญาตให้ Milo ใส่คำแปลไทยในวงเล็บ เช่น
 * "I am a big bear (หมี)." ซึ่งดีสำหรับการ **อ่าน** แต่พังสำหรับการ **ฟัง**
 * เพราะตัวอ่านภาษาอังกฤษไม่ว่าจะเป็นของเบราว์เซอร์หรือ Kokoro อ่านอักษรไทย
 * ไม่ได้ — ที่ได้ยินคือเงียบไปเฉย ๆ หรืออ่านเป็นเสียงมั่ว ๆ คั่นกลางประโยค
 *
 * บนจอยังเห็นคำแปลเหมือนเดิม ตัดเฉพาะตอนอ่านออกเสียง
 */
export function speakableText(text: string): string {
  return text
    // วงเล็บที่มีอักษรไทยอยู่ข้างใน ตัดทั้งวงเล็บ
    .replace(/\s*[([][^()[\]]*[\u0E00-\u0E7F][^()[\]]*[)\]]/g, "")
    // อักษรไทยที่หลุดมาเดี่ยว ๆ นอกวงเล็บ
    .replace(/[\u0E00-\u0E7F]+/g, "")
    .replace(/\s{2,}/g, " ")
    .replace(/\s+([.!?,])/g, "$1")
    .trim();
}
